-- =============================================================================
--  Integrated E-commerce Order Fulfillment & Logistics Management System
--  schema.sql  —  DDL (tables, constraints, indexes)
--
--  Run order:  schema.sql -> triggers.sql -> procedures.sql -> views.sql -> seed.sql
--  (or simply:  psql -d <db> -f db/init.sql)
--
--  Target: PostgreSQL 13+
-- =============================================================================

-- No extensions required: runs on a stock PostgreSQL install.
-- Passwords are stored as bcrypt hashes produced by the backend.

-- Drop in reverse dependency order so the script is re-runnable.
DROP TABLE IF EXISTS tracking_events, shipments, carriers, payments, order_items,
                     orders, inventory, warehouses, products, suppliers, categories,
                     addresses, customers, admins CASCADE;

-- -----------------------------------------------------------------------------
-- 1. CUSTOMERS
-- -----------------------------------------------------------------------------
CREATE TABLE customers (
    customer_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    phone          VARCHAR(15)  NOT NULL,
    password_hash  TEXT         NOT NULL,                       -- bcrypt hash
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT chk_customer_email CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT chk_customer_phone CHECK (phone ~ '^\+?[0-9]{10,14}$')
);

-- Admin accounts are a separate entity: they are not customers, never place
-- orders, and have no addresses.
CREATE TABLE admins (
    admin_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    password_hash  TEXT         NOT NULL,

    CONSTRAINT chk_admin_email CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

-- -----------------------------------------------------------------------------
-- 2. ADDRESSES  (customer 1 ── N addresses)
-- -----------------------------------------------------------------------------
CREATE TABLE addresses (
    address_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    INT          NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    line1          VARCHAR(200) NOT NULL,
    city           VARCHAR(80)  NOT NULL,
    state          VARCHAR(80)  NOT NULL,
    pincode        CHAR(6)      NOT NULL,

    CONSTRAINT chk_address_pincode CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    -- Needed as the target of the composite FK in ORDERS (see below).
    CONSTRAINT uq_address_customer UNIQUE (address_id, customer_id)
);
CREATE INDEX idx_addresses_customer ON addresses(customer_id);

-- -----------------------------------------------------------------------------
-- 3. CATEGORIES, SUPPLIERS, PRODUCTS
-- -----------------------------------------------------------------------------
CREATE TABLE categories (
    category_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE suppliers (
    supplier_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120) NOT NULL UNIQUE,
    contact_email  VARCHAR(150)
);

CREATE TABLE products (
    product_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id    INT           NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    supplier_id    INT           NOT NULL REFERENCES suppliers(supplier_id)  ON DELETE RESTRICT,
    name           VARCHAR(150)  NOT NULL,
    description    TEXT,
    price          NUMERIC(10,2) NOT NULL,

    CONSTRAINT chk_product_price CHECK (price > 0),
    CONSTRAINT uq_product_supplier_name UNIQUE (supplier_id, name)
);
CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_products_supplier ON products(supplier_id);
CREATE INDEX idx_products_name_lower ON products(lower(name));   -- catalog search

-- -----------------------------------------------------------------------------
-- 4. WAREHOUSES, INVENTORY  (product N ── M warehouse, with stock as attribute)
-- -----------------------------------------------------------------------------
CREATE TABLE warehouses (
    warehouse_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location       VARCHAR(120) NOT NULL UNIQUE,
    capacity       INT          NOT NULL,                        -- max units storable

    CONSTRAINT chk_warehouse_capacity CHECK (capacity > 0)
);

CREATE TABLE inventory (
    inventory_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     INT NOT NULL REFERENCES products(product_id)     ON DELETE CASCADE,
    warehouse_id   INT NOT NULL REFERENCES warehouses(warehouse_id) ON DELETE CASCADE,
    stock_qty      INT NOT NULL DEFAULT 0,
    reorder_level  INT NOT NULL DEFAULT 10,                      -- low-stock threshold

    CONSTRAINT chk_inventory_stock   CHECK (stock_qty >= 0),
    CONSTRAINT chk_inventory_reorder CHECK (reorder_level >= 0),
    -- One stock row per (product, warehouse). The unique index also serves
    -- lookups by product_id (leading column).
    CONSTRAINT uq_inventory_product_warehouse UNIQUE (product_id, warehouse_id)
);
CREATE INDEX idx_inventory_warehouse ON inventory(warehouse_id);

-- -----------------------------------------------------------------------------
-- 5. ORDERS, ORDER_ITEMS
-- -----------------------------------------------------------------------------
CREATE TABLE orders (
    order_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    INT         NOT NULL REFERENCES customers(customer_id) ON DELETE RESTRICT,
    address_id     INT         NOT NULL,
    order_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
    status         VARCHAR(20) NOT NULL DEFAULT 'pending',

    CONSTRAINT chk_order_status
        CHECK (status IN ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')),
    -- Composite FK: the delivery address must belong to the ordering customer.
    -- A plain FK on address_id alone would allow shipping to someone else's address.
    CONSTRAINT fk_order_address_customer
        FOREIGN KEY (address_id, customer_id)
        REFERENCES addresses(address_id, customer_id) ON DELETE RESTRICT
);
CREATE INDEX idx_orders_customer   ON orders(customer_id);
CREATE INDEX idx_orders_address    ON orders(address_id);
CREATE INDEX idx_orders_status     ON orders(status);
CREATE INDEX idx_orders_order_date ON orders(order_date);

-- Junction table resolving ORDERS ↔ PRODUCTS (M:N).
CREATE TABLE order_items (
    order_item_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       INT           NOT NULL REFERENCES orders(order_id)     ON DELETE CASCADE,
    product_id     INT           NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    -- Warehouse the line is fulfilled from. Filled in by the stock trigger when
    -- not supplied; NOT NULL is checked after BEFORE triggers run.
    warehouse_id   INT           NOT NULL REFERENCES warehouses(warehouse_id) ON DELETE RESTRICT,
    quantity       INT           NOT NULL,
    -- Price snapshot at purchase time: products.price may change later, so this
    -- is a separate historical fact, not a redundant copy.
    unit_price     NUMERIC(10,2) NOT NULL,

    CONSTRAINT chk_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_item_price    CHECK (unit_price > 0),
    CONSTRAINT uq_item_order_product UNIQUE (order_id, product_id)  -- also indexes order_id
);
CREATE INDEX idx_order_items_product   ON order_items(product_id);
CREATE INDEX idx_order_items_warehouse ON order_items(warehouse_id);

-- -----------------------------------------------------------------------------
-- 6. PAYMENTS  (order 1 ── 1 payment, enforced by UNIQUE on order_id)
-- -----------------------------------------------------------------------------
CREATE TABLE payments (
    payment_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       INT           NOT NULL UNIQUE REFERENCES orders(order_id) ON DELETE CASCADE,
    amount         NUMERIC(12,2) NOT NULL,
    method         VARCHAR(20)   NOT NULL,
    status         VARCHAR(20)   NOT NULL DEFAULT 'pending',
    paid_at        TIMESTAMPTZ,

    CONSTRAINT chk_payment_amount CHECK (amount > 0),
    CONSTRAINT chk_payment_method CHECK (method IN ('card', 'upi', 'netbanking', 'wallet', 'cod')),
    CONSTRAINT chk_payment_status CHECK (status IN ('pending', 'completed', 'failed', 'refunded')),
    CONSTRAINT chk_payment_paid_at CHECK (status IN ('pending', 'failed') OR paid_at IS NOT NULL)
);
CREATE INDEX idx_payments_status ON payments(status);

-- -----------------------------------------------------------------------------
-- 7. CARRIERS, SHIPMENTS, TRACKING_EVENTS
-- -----------------------------------------------------------------------------
CREATE TABLE carriers (
    carrier_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL UNIQUE
);

-- An order may be split into several shipments (one per fulfilling warehouse),
-- so order_id is NOT unique here.
CREATE TABLE shipments (
    shipment_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INT         NOT NULL REFERENCES orders(order_id)         ON DELETE CASCADE,
    warehouse_id    INT         NOT NULL REFERENCES warehouses(warehouse_id) ON DELETE RESTRICT,
    carrier_id      INT         NOT NULL REFERENCES carriers(carrier_id)     ON DELETE RESTRICT,
    tracking_number VARCHAR(40) NOT NULL UNIQUE DEFAULT ('TRK' || upper(substr(md5(random()::text), 1, 10))),
    status          VARCHAR(20) NOT NULL DEFAULT 'label_created',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_shipment_status
        CHECK (status IN ('label_created', 'in_transit', 'out_for_delivery', 'delivered', 'failed')),
    CONSTRAINT uq_shipment_order_warehouse UNIQUE (order_id, warehouse_id)  -- also indexes order_id
);
CREATE INDEX idx_shipments_warehouse ON shipments(warehouse_id);
CREATE INDEX idx_shipments_carrier   ON shipments(carrier_id);
CREATE INDEX idx_shipments_status    ON shipments(status);

CREATE TABLE tracking_events (
    event_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id    INT          NOT NULL REFERENCES shipments(shipment_id) ON DELETE CASCADE,
    location       VARCHAR(120) NOT NULL,
    event_time     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    status         VARCHAR(20)  NOT NULL,

    CONSTRAINT chk_event_status
        CHECK (status IN ('picked_up', 'in_transit', 'arrived_at_hub',
                          'out_for_delivery', 'delivered', 'delivery_failed'))
);
-- Composite index: "timeline for shipment X ordered by time" is the hot query.
CREATE INDEX idx_tracking_shipment_time ON tracking_events(shipment_id, event_time);
CREATE INDEX idx_tracking_status        ON tracking_events(status);
